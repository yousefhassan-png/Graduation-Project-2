from cleaning import حمل_البيانات_النظيفة
from analysis import اختبار_الخصم, قسم_العملاء

البيانات, ملخص = حمل_البيانات_النظيفة()
عدد_الشاذ = int(البيانات['كمية_شاذة'].sum())
البيانات = البيانات[~البيانات['كمية_شاذة']]

الإيراد_الكلي = البيانات['الإيراد'].sum()
قيمة_الخصومات = البيانات['قيمة_الخصم'].sum()
نسبة_الخصومات = قيمة_الخصومات / البيانات['الإيراد_قبل_الخصم'].sum() * 100
حسب_المدينة = البيانات.groupby('المدينة')['الإيراد'].sum().sort_values(ascending=False)
حسب_الفئة = البيانات.groupby('الفئة')['الإيراد'].sum().sort_values(ascending=False)
الشهري = البيانات.groupby('الشهر')['الإيراد'].sum()
بدون_سبتمبر = الشهري.drop('2026-09')
سبتمبر = البيانات[البيانات['الشهر'] == '2026-09']
حصة_القرطاسية_سبتمبر = سبتمبر[سبتمبر['الفئة'] == 'قرطاسية']['الإيراد'].sum() / سبتمبر['الإيراد'].sum() * 100
باقي = البيانات[البيانات['الشهر'] != '2026-09']
حصة_القرطاسية_باقي = باقي[باقي['الفئة'] == 'قرطاسية']['الإيراد'].sum() / باقي['الإيراد'].sum() * 100
النتيجة = اختبار_الخصم(البيانات)
جدول_العملاء = قسم_العملاء(البيانات)
الشرائح = جدول_العملاء.groupby('الشريحة').agg(عدد=('الإنفاق', 'size'), مجموع=('الإنفاق', 'sum'), غياب=('الحداثة', 'mean'))
الشرائح['نسبة'] = الشرائح['مجموع'] / الشرائح['مجموع'].sum() * 100
البيانات['سبتمبر'] = البيانات['الشهر'] == '2026-09'
طلبات_الفئة = البيانات.groupby(['الفئة', 'سبتمبر']).size().unstack()
ضعف_القرطاسية = طلبات_الفئة.loc['قرطاسية', True] / (طلبات_الفئة.loc['قرطاسية', False] / 8)
طلبات_المدينة = البيانات.groupby(['المدينة', 'سبتمبر']).size().unstack()
ضعف_المدينة = (طلبات_المدينة[True] / (طلبات_المدينة[False] / 8)).sort_values(ascending=False)
قيمة_الطلب_سبتمبر = سبتمبر['الإيراد'].mean()
قيمة_الطلب_باقي = باقي['الإيراد'].mean()
مدن_صغيرة = حسب_المدينة.tail(2)

التقرير = f'''## 1. سؤال البزنس
كيف نزيد إيرادات المتجر من دون أن نخسر أرباحنا على الخصومات؟ حللنا مبيعات 9 أشهر (يناير إلى سبتمبر 2026) لنعرف من أين يأتي الإيراد، وهل الخصومات التي نقدمها تدفع الزبائن لشراء أكثر.

## 2. أهم الرؤى
- **الإيراد الكلي {الإيراد_الكلي:,.0f} دينار**، وأكثر من نصفه يأتي من فئتين: {حسب_الفئة.index[0]} ({حسب_الفئة.iloc[0] / الإيراد_الكلي * 100:.0f}%) و{حسب_الفئة.index[1]} ({حسب_الفئة.iloc[1] / الإيراد_الكلي * 100:.0f}%).
- **مدينة {حسب_المدينة.index[0]} هي قلب المبيعات** بحصة {حسب_المدينة.iloc[0] / الإيراد_الكلي * 100:.0f}% من الإيراد، بينما {مدن_صغيرة.index[1]} و{مدن_صغيرة.index[0]} أصغر المدن (حوالي {(مدن_صغيرة.sum() / الإيراد_الكلي * 100):.0f}% معًا).
- **سبتمبر شهر استثنائي:** إيراده {الشهري["2026-09"]:,.0f} دينار، أي ضعف أي شهر آخر تقريبًا (باقي الأشهر بين {بدون_سبتمبر.min():,.0f} و{بدون_سبتمبر.max():,.0f}). والسبب الأوضح القرطاسية: طلباتها في سبتمبر بلغت {ضعف_القرطاسية:.1f} ضعف الشهر العادي، وشكلت {حصة_القرطاسية_سبتمبر:.0f}% من إيراد الشهر مقابل {حصة_القرطاسية_باقي:.0f}% في بقية الأشهر. وهذا يتوافق مع موسم العودة للمدارس.
- **الخصومات كلّفتنا {قيمة_الخصومات:,.0f} دينار** ({نسبة_الخصومات:.1f}% من قيمة المبيعات) دون أثر واضح على الكميات المباعة.

## 3. هل الخصم يجعل الزبائن يشترون أكثر؟
لا يوجد دليل على ذلك. الطلب المخفض يباع منه {النتيجة["متوسط_بخصم"]:.1f} قطعة في المتوسط والطلب بدون خصم {النتيجة["متوسط_بدون_خصم"]:.1f} قطعة، وهذا الفرق صغير جدًا ويُحتمل أن يكون صدفة. وحتى عندما فحصنا كل فئة لوحدها لم نجد فئة تتجاوب بوضوح مع الخصم.

## 4. التحليل الإضافي: الاتجاه الزمني ومجموعات العملاء
- **الاتجاه الزمني:** باستثناء سبتمبر، الإيراد الشهري في نمو بطيء ومتذبذب (من {الشهري.iloc[0]:,.0f} دينار في يناير إلى {الشهري["2026-08"]:,.0f} دينار في أغسطس، مع هبوط في فبراير). أما قفزة سبتمبر فجاءت من **كثرة الطلبات** وليس من طلبات أغلى (متوسط قيمة الطلب في سبتمبر {قيمة_الطلب_سبتمبر:,.0f} دينار مقابل {قيمة_الطلب_باقي:,.0f} في باقي الأشهر)، وظهرت في كل المدن وأقواها في {ضعف_المدينة.index[0]} ({ضعف_المدينة.iloc[0]:.1f} ضعف) و{ضعف_المدينة.index[1]} ({ضعف_المدينة.iloc[1]:.1f} ضعف).
- **مجموعات العملاء:** قسمنا العملاء حسب حداثة الشراء وعدد المشتريات وقيمتها إلى ثلاث مجموعات: **{int(الشرائح.loc["عملاء كبار","عدد"])} عميلًا كبيرًا** يجلبون {الشرائح.loc["عملاء كبار","نسبة"]:.0f}% من الإيراد، و**{int(الشرائح.loc["عملاء عاديون","عدد"])} عميلًا عاديًا** ({الشرائح.loc["عملاء عاديون","نسبة"]:.0f}%)، و**{int(الشرائح.loc["عملاء خاملون","عدد"])} عملاء خاملين** لم يشتروا منذ حوالي {الشرائح.loc["عملاء خاملون","غياب"]:.0f} يومًا ({الشرائح.loc["عملاء خاملون","نسبة"]:.0f}% من الإيراد). الاستنتاج: أقل من نصف عملائنا يجلبون حوالي ثلاثة أخماس إيرادنا.

## 5. ثلاث توصيات عملية
1. **أوقفوا الخصومات العامة وجرّبوا خصمًا محدودًا:** الخصم لا يزيد الكمية، فالأفضل تثبيت الأسعار وتوفير حوالي {قيمة_الخصومات:,.0f} دينار تقريبًا، أو تجربة خصم صغير على فئة واحدة لمدة شهر ومقارنتها بفئة بدون خصم قبل التوسع.
2. **جهّزوا موسم سبتمبر مبكرًا:** زيدوا مخزون القرطاسية وطاقم المبيعات من آخر أغسطس، وادفعوا بإعلانات المدارس خصوصًا في {ضعف_المدينة.index[0]} و{ضعف_المدينة.index[1]}، لأن طلبات القرطاسية تتضاعف {ضعف_القرطاسية:.0f} مرات تقريبًا في هذا الشهر.
3. **احموا العملاء الكبار واستعيدوا الخاملين:** الـ {int(الشرائح.loc["عملاء كبار","عدد"])} عميلًا الكبار يجلبون {الشرائح.loc["عملاء كبار","نسبة"]:.0f}% من الإيراد، فخصّوهم بخدمة ومتابعة مميزة (بدل خصومات عامة). وتواصلوا شخصيًا مع العملاء الخاملين الـ {int(الشرائح.loc["عملاء خاملون","عدد"])} لمعرفة سبب غيابهم وعرض عودة محدد.

## ملاحظة على جودة البيانات
استبعدنا {عدد_الشاذ} طلبًا كمياتها غير منطقية (مثل 250 دبّاسة في طلب واحد) لأنها غالبًا أخطاء إدخال. أنصح بإضافة تحقق عند إدخال الكمية لمنع تكرارها.
'''

with open('executive_report.md', 'w', encoding='utf-8') as ملف:
    ملف.write(التقرير)
