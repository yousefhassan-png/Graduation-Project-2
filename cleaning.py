    print('القرار: نستثني هذه الصفوف من المؤشرات لأنها غالبًا أخطاء إدخال (مثل 250 دبّاسة في طلب واحد).')
    البيانات.to_csv('store_clean.csv', index=False, encoding='utf-8-sig')
