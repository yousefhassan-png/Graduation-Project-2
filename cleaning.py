import sqlite3
import pandas as pd

اسم_قاعدة_البيانات = 'store.db'


def حمل_البيانات_الخام(مسار_القاعدة=اسم_قاعدة_البيانات):
    # نقرأ الجداول الثلاثة (sales و products و customers) بالاستعلام نفسه عن طريق JOIN
    الاتصال = sqlite3.connect(مسار_القاعدة)
    الاستعلام = '''
        SELECT s.sale_id        AS رقم_البيع,
               s.sale_date      AS تاريخ_البيع,
               s.city           AS المدينة,
               s.quantity       AS الكمية,
               s.discount       AS نسبة_الخصم,
               s.payment_method AS طريقة_الدفع,
               s.customer_id    AS رقم_العميل,
               c.customer_name  AS اسم_العميل,
               c.join_date      AS تاريخ_انضمام_العميل,
               p.product_name   AS المنتج,
               p.category       AS الفئة_بالانجليزي,
               p.price          AS سعر_الوحدة
        FROM sales s
        JOIN products  p ON s.product_id  = p.product_id
        JOIN customers c ON s.customer_id = c.customer_id
    '''
    البيانات = pd.read_sql(الاستعلام, الاتصال)
    الاتصال.close()
    return البيانات


# ترجمة القيم الإنجليزية إلى العربية لتظهر مفهومة في اللوحة
ترجمة_الفئات = {
    'electronics': 'إلكترونيات',
    'furniture': 'أثاث',
    'stationery': 'قرطاسية',
    'accessories': 'إكسسوارات',
    'appliances': 'أجهزة منزلية',
}
ترجمة_طرق_الدفع = {'cash': 'نقدًا', 'card': 'بطاقة', 'transfer': 'حوالة'}


def نظف_البيانات(البيانات):
    البيانات = البيانات.copy()

    # 1) فحص القيم الفارغة والصفوف المكررة
    عدد_الفارغ = int(البيانات.isnull().sum().sum())
    عدد_المكرر = int(البيانات.duplicated(subset=['رقم_البيع']).sum())
    البيانات = البيانات.drop_duplicates(subset=['رقم_البيع'])

    # 2) تحويل التواريخ من نص إلى تاريخ حقيقي
    البيانات['تاريخ_البيع'] = pd.to_datetime(البيانات['تاريخ_البيع'])
    البيانات['تاريخ_انضمام_العميل'] = pd.to_datetime(البيانات['تاريخ_انضمام_العميل'])

    # 3) ترجمة الفئات وطرق الدفع
    البيانات['الفئة'] = البيانات['الفئة_بالانجليزي'].map(ترجمة_الفئات)
    البيانات['طريقة_الدفع'] = البيانات['طريقة_الدفع'].map(ترجمة_طرق_الدفع)

    # 4) حساب الأعمدة المالية
    البيانات['الإيراد_قبل_الخصم'] = البيانات['الكمية'] * البيانات['سعر_الوحدة']
    البيانات['قيمة_الخصم'] = البيانات['الإيراد_قبل_الخصم'] * البيانات['نسبة_الخصم']
    البيانات['الإيراد'] = البيانات['الإيراد_قبل_الخصم'] - البيانات['قيمة_الخصم']

    # 5) أعمدة مساعدة للتحليل
    البيانات['الشهر'] = البيانات['تاريخ_البيع'].dt.strftime('%Y-%m')
    البيانات['فيه_خصم'] = البيانات['نسبة_الخصم'] > 0
    البيانات['نوع_الطلب'] = البيانات['فيه_خصم'].map({True: 'بخصم', False: 'بدون خصم'})

    # 6) القيم الشاذة في الكمية بطريقة IQR (نفس طريقة التاسك السابقة)
    الربيع_الأول = البيانات['الكمية'].quantile(0.25)
    الربيع_الثالث = البيانات['الكمية'].quantile(0.75)
    المدى_الربيعي = الربيع_الثالث - الربيع_الأول
    الحد_الأعلى = الربيع_الثالث + 1.5 * المدى_الربيعي
    البيانات['كمية_شاذة'] = البيانات['الكمية'] > الحد_الأعلى

    ملخص = {'فارغ': عدد_الفارغ, 'مكرر': عدد_المكرر, 'حد_الكمية': الحد_الأعلى}
    return البيانات, ملخص


def حمل_البيانات_النظيفة(مسار_القاعدة=اسم_قاعدة_البيانات):
    البيانات, ملخص = نظف_البيانات(حمل_البيانات_الخام(مسار_القاعدة))
    return البيانات, ملخص


if __name__ == '__main__':
    البيانات, ملخص = حمل_البيانات_النظيفة()
    print('عدد الصفوف والأعمدة:', البيانات.shape)
    print('عدد القيم الفارغة:', ملخص['فارغ'], '، عدد الصفوف المكررة:', ملخص['مكرر'])
