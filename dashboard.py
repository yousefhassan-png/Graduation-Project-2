# =====================================================================
import streamlit as st
import pandas as pd
import plotly.express as px
import seaborn as sns
import matplotlib.pyplot as plt

from cleaning import حمل_البيانات_النظيفة
from analysis import اختبار_الخصم, قسم_العملاء, أضف_الشريحة

try:
    import arabic_reshaper
    from bidi.algorithm import get_display

    def عربي(النص):
        return get_display(arabic_reshaper.reshape(str(النص)))
except ImportError:
    def عربي(النص):
        return str(النص)

st.set_page_config(page_title='لوحة مبيعات المتجر', page_icon='🛒', layout='wide')

# نجعل الصفحة من اليمين لليسار لتناسب العربية
st.markdown('''
<style>
html, body, [data-testid="stAppViewContainer"], [data-testid="stSidebar"] { direction: rtl; text-align: right; }
[data-testid="stMetric"] { text-align: right; }
</style>
''', unsafe_allow_html=True)


# ---------------------------------------------------------------------
# تحميل البيانات (نخزنها بالذاكرة حتى لا تُقرأ في كل نقرة)
# ---------------------------------------------------------------------
@st.cache_data
def جهز_البيانات():
    البيانات, ملخص = حمل_البيانات_النظيفة()
    # نقسم العملاء (RFM + K-Means) على كل البيانات السليمة، ثم نضيف الشريحة لكل عملية
    جدول_العملاء = قسم_العملاء(البيانات[~البيانات['كمية_شاذة']])
    البيانات = أضف_الشريحة(البيانات, جدول_العملاء)
    البيانات['الشريحة'] = البيانات['الشريحة'].fillna('غير مصنف')
    return البيانات, ملخص


def قارن_سبتمبر(بيانات):
    # عدد طلبات كل فئة في سبتمبر مقارنة بمتوسط الشهر في باقي الأشهر المختارة
    سبتمبر_فقط = بيانات[بيانات['الشهر'] == '2026-09']
    باقي_الأشهر = بيانات[بيانات['الشهر'] != '2026-09']
    if len(سبتمبر_فقط) == 0 or len(باقي_الأشهر) == 0:
        return None
    عدد_الأشهر = باقي_الأشهر['الشهر'].nunique()
    الجدول = pd.DataFrame({'سبتمبر': سبتمبر_فقط.groupby('الفئة').size(),
                           'متوسط_شهر': باقي_الأشهر.groupby('الفئة').size() / عدد_الأشهر}).dropna()
    الجدول['كم_ضعف'] = الجدول['سبتمبر'] / الجدول['متوسط_شهر']
    return الجدول.reset_index().sort_values('كم_ضعف', ascending=False)


كل_البيانات, ملخص_التنظيف = جهز_البيانات()

st.title('🛒 لوحة تحكم مبيعات المتجر')
st.caption('بيانات المبيعات من 1 يناير حتى 30 سبتمبر 2026 - المبالغ بالدينار (افتراضيًا)')

# ---------------------------------------------------------------------
# الشريط الجانبي: الفلاتر
# ---------------------------------------------------------------------
st.sidebar.header('🔎 الفلاتر')

أقدم_تاريخ = كل_البيانات['تاريخ_البيع'].min().date()
أحدث_تاريخ = كل_البيانات['تاريخ_البيع'].max().date()
الفترة = st.sidebar.date_input('الفترة الزمنية', value=(أقدم_تاريخ, أحدث_تاريخ),
                               min_value=أقدم_تاريخ, max_value=أحدث_تاريخ)
# أثناء اختيار التاريخ قد يرجع تاريخ واحد فقط، فنتأكد
if isinstance(الفترة, tuple) and len(الفترة) == 2:
    من_تاريخ, إلى_تاريخ = الفترة
else:
    من_تاريخ, إلى_تاريخ = أقدم_تاريخ, أحدث_تاريخ

قائمة_المدن = sorted(كل_البيانات['المدينة'].unique())
المدن_المختارة = st.sidebar.multiselect('المدينة', قائمة_المدن, default=قائمة_المدن)

قائمة_الفئات = sorted(كل_البيانات['الفئة'].unique())
الفئات_المختارة = st.sidebar.multiselect('فئة المنتج', قائمة_الفئات, default=قائمة_الفئات)

قائمة_الدفع = sorted(كل_البيانات['طريقة_الدفع'].unique())
الدفع_المختار = st.sidebar.multiselect('طريقة الدفع', قائمة_الدفع, default=قائمة_الدفع)

قائمة_الشرائح = sorted(كل_البيانات['الشريحة'].unique())
الشرائح_المختارة = st.sidebar.multiselect('شريحة العميل', قائمة_الشرائح, default=قائمة_الشرائح,
                                          help='تقسيم العملاء بطريقة RFM مع K-Means')

نوع_الخصم = st.sidebar.radio('نوع الطلب', ['الكل', 'بخصم', 'بدون خصم'])

استبعاد_الشاذ = st.sidebar.checkbox(
    f'استبعاد الطلبات ذات الكمية الشاذة ({int(كل_البيانات["كمية_شاذة"].sum())} طلب)', value=True,
    help='طلبات كميتها أكبر من %.0f قطعة، غالبًا أخطاء إدخال' % ملخص_التنظيف['حد_الكمية'])

# ---------------------------------------------------------------------
# تطبيق الفلاتر
# ---------------------------------------------------------------------
البيانات = كل_البيانات[
    (كل_البيانات['تاريخ_البيع'].dt.date >= من_تاريخ) &
    (كل_البيانات['تاريخ_البيع'].dt.date <= إلى_تاريخ) &
    (كل_البيانات['المدينة'].isin(المدن_المختارة)) &
    (كل_البيانات['الفئة'].isin(الفئات_المختارة)) &
    (كل_البيانات['طريقة_الدفع'].isin(الدفع_المختار)) &
    (كل_البيانات['الشريحة'].isin(الشرائح_المختارة))
]
if نوع_الخصم != 'الكل':
    البيانات = البيانات[البيانات['نوع_الطلب'] == نوع_الخصم]
if استبعاد_الشاذ:
    البيانات = البيانات[~البيانات['كمية_شاذة']]

st.sidebar.markdown('---')
st.sidebar.write(f'عدد الطلبات بعد الفلترة: **{len(البيانات):,}** من {len(كل_البيانات):,}')

if البيانات.empty:
    st.warning('لا توجد بيانات تطابق هذه الفلاتر، جرّب توسيع الاختيار.')
    st.stop()

# ---------------------------------------------------------------------
# حساب المؤشرات
# ---------------------------------------------------------------------
الإيراد_الكلي = البيانات['الإيراد'].sum()
متوسط_الطلب = البيانات['الإيراد'].mean()
قيمة_الخصومات = البيانات['قيمة_الخصم'].sum()
نسبة_الخصومات = قيمة_الخصومات / البيانات['الإيراد_قبل_الخصم'].sum() * 100
إنفاق_العميل = الإيراد_الكلي / البيانات['رقم_العميل'].nunique()

تبويب_اللوحة, تبويب_الملخص = st.tabs(['📊 لوحة التحكم', '📝 الملخص التنفيذي'])

with تبويب_اللوحة:
    # ------------------- صف المؤشرات -------------------
    ع1, ع2, ع3, ع4 = st.columns(4)
    ع1.metric('إجمالي الإيراد', f'{الإيراد_الكلي:,.0f} د')
    ع2.metric('متوسط قيمة الطلب', f'{متوسط_الطلب:,.0f} د')
    ع3.metric('الخصومات من المبيعات', f'{نسبة_الخصومات:.1f}%', help=f'قيمتها {قيمة_الخصومات:,.0f} دينار')
    ع4.metric('متوسط إنفاق العميل', f'{إنفاق_العميل:,.0f} د')

    st.markdown('---')

    # ------------------- الرسمة 1: الاتجاه الزمني (Plotly) -------------------
    st.subheader('هل مبيعاتنا تنمو؟ الإيراد الشهري')
    الشهري = البيانات.groupby('الشهر', as_index=False).agg(الإيراد=('الإيراد', 'sum'), عدد_الطلبات=('رقم_البيع', 'count'))
    الرسمة_1 = px.line(الشهري, x='الشهر', y='الإيراد', markers=True, hover_data=['عدد_الطلبات'])
    الرسمة_1.update_layout(xaxis_title='الشهر', yaxis_title='الإيراد (دينار)')
    st.plotly_chart(الرسمة_1, width='stretch')

    الصف_الأول, الصف_الثاني = st.columns(2)

    # ------------------- الرسمة 2: الإيراد حسب المدينة (Seaborn) -------------------
    with الصف_الأول:
        st.subheader('عمّان تقود المبيعات، فأين بقية المدن؟')
        حسب_المدينة = البيانات.groupby('المدينة', as_index=False)['الإيراد'].sum().sort_values('الإيراد', ascending=False)
        حسب_المدينة['المدينة_معروضة'] = حسب_المدينة['المدينة'].apply(عربي)
        الشكل, المحور = plt.subplots(figsize=(6, 4))
        sns.barplot(data=حسب_المدينة, x='المدينة_معروضة', y='الإيراد', color='steelblue', ax=المحور)
        المحور.set_xlabel('')
        المحور.set_ylabel(عربي('الإيراد (دينار)'))
        plt.xticks(rotation=30)
        plt.tight_layout()
        st.pyplot(الشكل)

    # ------------------- الرسمة 3: الإيراد حسب الفئة (Plotly) -------------------
    with الصف_الثاني:
        st.subheader('أي الفئات تجلب أكبر حصة من الإيراد؟')
        حسب_الفئة = البيانات.groupby('الفئة', as_index=False)['الإيراد'].sum()
        الرسمة_3 = px.pie(حسب_الفئة, names='الفئة', values='الإيراد', hole=0.4)
        st.plotly_chart(الرسمة_3, width='stretch')

    الصف_الثالث, الصف_الرابع = st.columns(2)

    # ------------------- الرسمة 4: هل الخصم يرفع الكمية؟ (اختبار الفرضية) -------------------
    with الصف_الثالث:
        st.subheader('هل الخصم يجعل الزبون يشتري أكثر؟')
        حسب_الخصم = البيانات.groupby('نسبة_الخصم', as_index=False).agg(متوسط_الكمية=('الكمية', 'mean'), عدد_الطلبات=('رقم_البيع', 'count'))
        حسب_الخصم['الخصم'] = (حسب_الخصم['نسبة_الخصم'] * 100).astype(int).astype(str) + '%'
        الرسمة_4 = px.bar(حسب_الخصم, x='الخصم', y='متوسط_الكمية', hover_data=['عدد_الطلبات'], text_auto='.1f')
        الرسمة_4.update_layout(xaxis_title='نسبة الخصم', yaxis_title='متوسط الكمية في الطلب')
        st.plotly_chart(الرسمة_4, width='stretch')

    # ------------------- الرسمة 5: أفضل المنتجات (Plotly) -------------------
    with الصف_الرابع:
        st.subheader('أعلى 10 منتجات إيرادًا')
        حسب_المنتج = البيانات.groupby('المنتج', as_index=False)['الإيراد'].sum().sort_values('الإيراد', ascending=False).head(10)
        الرسمة_5 = px.bar(حسب_المنتج.sort_values('الإيراد'), x='الإيراد', y='المنتج', orientation='h')
        الرسمة_5.update_layout(xaxis_title='الإيراد (دينار)', yaxis_title='')
        st.plotly_chart(الرسمة_5, width='stretch')

    الصف_الخامس, الصف_السادس = st.columns(2)

    # ------------------- الرسمة 6: تفسير سبتمبر -------------------
    with الصف_الخامس:
        st.subheader('ما سر قفزة سبتمبر؟ القرطاسية')
        مقارنة_سبتمبر = قارن_سبتمبر(البيانات)
        if مقارنة_سبتمبر is None:
            st.info('اختر فترة تشمل سبتمبر وأشهرًا أخرى لتظهر المقارنة.')
        else:
            الرسمة_6 = px.bar(مقارنة_سبتمبر, x='الفئة', y='كم_ضعف', text_auto='.1f')
            الرسمة_6.add_hline(y=1, line_dash='dash', annotation_text='مستوى الشهر العادي')
            الرسمة_6.update_layout(xaxis_title='', yaxis_title='طلبات سبتمبر كم ضعف المعتاد')
            st.plotly_chart(الرسمة_6, width='stretch')

    # ------------------- الرسمة 7: شرائح العملاء -------------------
    with الصف_السادس:
        st.subheader('من يجلب إيرادنا؟ شرائح العملاء')
        حسب_الشريحة = البيانات.groupby('الشريحة', as_index=False).agg(
            الإيراد=('الإيراد', 'sum'), عدد_العملاء=('رقم_العميل', 'nunique'))
        الرسمة_7 = px.bar(حسب_الشريحة, x='الشريحة', y='الإيراد', hover_data=['عدد_العملاء'], text_auto='.3s')
        الرسمة_7.update_layout(xaxis_title='', yaxis_title='الإيراد (دينار)')
        st.plotly_chart(الرسمة_7, width='stretch')

    st.markdown('---')

    # ------------------- نتيجة اختبار الفرضية (واضحة وليست مخبأة بالكود) -------------------
    st.subheader('🧪 نتيجة اختبار الفرضية: هل الخصم يرفع الكمية المباعة؟')
    النتيجة = اختبار_الخصم(البيانات)
    if النتيجة is None:
        st.info('عدد الطلبات بخصم أو بدون خصم قليل جدًا ضمن هذه الفلاتر، لا يمكن إجراء الاختبار. وسّع الفلاتر.')
    else:
        الجملة_الأساسية = (f'الطلبات المخفضة تباع منها {النتيجة["متوسط_بخصم"]:.1f} قطعة في المتوسط، '
                           f'مقابل {النتيجة["متوسط_بدون_خصم"]:.1f} قطعة للطلبات بدون خصم. ')
        if النتيجة['قيمة_p'] < 0.05:
            st.success(الجملة_الأساسية + 'الفرق حقيقي وليس صدفة، فالخصم يرتبط فعلًا بزيادة الكمية.')
        else:
            st.warning(الجملة_الأساسية + 'الفرق صغير ويُحتمل أنه صدفة، فلا يوجد دليل كافٍ على أن الخصم يجعل الزبائن يشترون أكثر.')
        with st.expander('التفاصيل الإحصائية (للمختصين)'):
            st.write(f'اختبار t لعينتين مستقلتين (Welch)، قيمة p = {النتيجة["قيمة_p"]:.3f} '
                     f'({النتيجة["عدد_بخصم"]} طلب بخصم، {النتيجة["عدد_بدون_خصم"]} طلب بدون خصم)')

    st.markdown('---')

    # ------------------- أهم الملاحظات (تتحدث مع الفلاتر) -------------------
    st.subheader('💡 أهم الملاحظات')
    أفضل_مدينة = البيانات.groupby('المدينة')['الإيراد'].sum().sort_values(ascending=False)
    أفضل_فئة = البيانات.groupby('الفئة')['الإيراد'].sum().sort_values(ascending=False)
    نص_سبتمبر = ''
    if مقارنة_سبتمبر is not None and 'قرطاسية' in set(مقارنة_سبتمبر['الفئة']):
        ضعف_القرطاسية = مقارنة_سبتمبر[مقارنة_سبتمبر['الفئة'] == 'قرطاسية']['كم_ضعف'].iloc[0]
        نص_سبتمبر = f'وفي سبتمبر وصلت طلبات القرطاسية إلى **{ضعف_القرطاسية:.1f} ضعف** معدل الشهر العادي (موسم العودة للمدارس غالبًا).'
    st.markdown(f'''
1. **التركّز:** مدينة **{أفضل_مدينة.index[0]}** تجلب **{أفضل_مدينة.iloc[0] / الإيراد_الكلي * 100:.0f}%** من الإيراد، وفئة **{أفضل_فئة.index[0]}** هي الأكبر بحصة **{أفضل_فئة.iloc[0] / الإيراد_الكلي * 100:.0f}%**.
2. **الخصومات:** كلّفتنا الخصومات **{قيمة_الخصومات:,.0f} دينار** ({نسبة_الخصومات:.1f}% من المبيعات)، وحسب نتيجة الاختبار أعلاه لا يظهر أنها تضيف كميات مباعة بشكل مؤكد.
3. **الموسم:** أعلى شهر إيرادًا ضمن اختيارك هو **{الشهري.sort_values("الإيراد").iloc[-1]["الشهر"]}** بإيراد **{الشهري["الإيراد"].max():,.0f} دينار**. {نص_سبتمبر}
''')

with تبويب_الملخص:
    st.header('الملخص التنفيذي')
    try:
        with open('executive_report.md', encoding='utf-8') as الملف:
            st.markdown(الملف.read())
    except FileNotFoundError:
        st.info('شغّل report.py أولًا لإنشاء ملف executive_report.md')
