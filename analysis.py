import pandas as pd
from scipy import stats
from sklearn.cluster import KMeans
from sklearn.preprocessing import StandardScaler
from cleaning import حمل_البيانات_النظيفة


def اختبار_الخصم(بيانات):
    # نقارن متوسط الكمية بين الطلبات المخفضة وغير المخفضة (اختبار t لعينتين)
    مخفض = بيانات[بيانات['فيه_خصم']]['الكمية']
    غير_مخفض = بيانات[~بيانات['فيه_خصم']]['الكمية']
    if len(مخفض) < 5 or len(غير_مخفض) < 5:
        return None   # العينة صغيرة جدًا ولا يصح الاختبار
    نتيجة = stats.ttest_ind(مخفض, غير_مخفض, equal_var=False)  # Welch
    return {
        'متوسط_بخصم': مخفض.mean(),
        'متوسط_بدون_خصم': غير_مخفض.mean(),
        'عدد_بخصم': len(مخفض),
        'عدد_بدون_خصم': len(غير_مخفض),
        'قيمة_p': نتيجة.pvalue,
    }


def قسم_العملاء(بيانات):
    # تقسيم العملاء بطريقة RFM:
    #   R = كم يوم مضى على آخر شراء (الحداثة)
    #   F = عدد مرات الشراء (التكرار)
    #   M = مجموع ما أنفقه (القيمة المالية)
    يوم_المقارنة = بيانات['تاريخ_البيع'].max() + pd.Timedelta(days=1)
    جدول = بيانات.groupby('رقم_العميل').agg(
        الحداثة=('تاريخ_البيع', lambda التواريخ: (يوم_المقارنة - التواريخ.max()).days),
        التكرار=('رقم_البيع', 'count'),
        الإنفاق=('الإيراد', 'sum'))
    # نوحّد المقاييس حتى لا يطغى رقم على آخر، ثم نقسم لـ 3 مجموعات
    الأرقام_الموحدة = StandardScaler().fit_transform(جدول)
    جدول['مجموعة'] = KMeans(n_clusters=3, n_init=10, random_state=42).fit_predict(الأرقام_الموحدة)

    # نسمي كل مجموعة حسب خصائصها: الأبعد زمنًا = خاملون، والأعلى إنفاقًا من الباقي = كبار
    المتوسطات = جدول.groupby('مجموعة')[['الحداثة', 'الإنفاق']].mean()
    الخاملة = المتوسطات['الحداثة'].idxmax()
    الكبار = المتوسطات.drop(الخاملة)['الإنفاق'].idxmax()
    الأسماء = {}
    for رقم in المتوسطات.index:
        if رقم == الخاملة:
            الأسماء[رقم] = 'عملاء خاملون'
        elif رقم == الكبار:
            الأسماء[رقم] = 'عملاء كبار'
        else:
            الأسماء[رقم] = 'عملاء عاديون'
    جدول['الشريحة'] = جدول['مجموعة'].map(الأسماء)
    return جدول


def أضف_الشريحة(بيانات, جدول_العملاء):
    # نضيف عمود الشريحة لكل عملية بيع حسب عميلها
    return بيانات.merge(جدول_العملاء[['الشريحة']], left_on='رقم_العميل', right_index=True, how='left')


